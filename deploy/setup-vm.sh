#!/usr/bin/env bash
# One-time preparation of a fresh Ubuntu server (written for Oracle Cloud Ampere A1, 24.04).
# Run from the repository root:   ./deploy/setup-vm.sh
# It installs Docker from Ubuntu's own packages, adds swap, and creates .env with fresh random
# secrets if there is none. Safe to run twice. It does not start the app and opens no ports.
# NOT yet run on a real Oracle machine: read it before you run it.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ "${KLIERLY_SKIP_SYSTEM:-0}" != "1" ]; then
  if ! command -v docker >/dev/null 2>&1; then
    sudo apt-get update
    sudo apt-get install -y docker.io docker-compose-v2 git curl
  fi
  sudo usermod -aG docker "$USER" || true

  # The Next.js build needs more memory than a small server comfortably has; swap is the safety net.
  if ! swapon --show | grep -q '^/swapfile'; then
    sudo fallocate -l 4G /swapfile
    sudo chmod 600 /swapfile
    sudo mkswap /swapfile >/dev/null
    sudo swapon /swapfile
    grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab >/dev/null
    echo "Added 4 GB of swap."
  fi
fi

if [ -f .env ]; then
  echo ".env already exists: left unchanged."
else
  umask 077
  cat > .env <<ENV
# Generated by deploy/setup-vm.sh on $(date -u +%Y-%m-%dT%H:%MZ). Keep this file private; never commit it.
POSTGRES_PASSWORD=$(openssl rand -hex 16)
WORKER_TOKEN=$(openssl rand -hex 24)
APP_SECRET=$(openssl rand -base64 48 | tr -d '\n')
# Private access through an SSH tunnel: leave as is. For a public https site, set your address instead.
APP_URL=http://localhost:3000
# Required (and must be long) before anyone but you can reach the site. Share it only with people you invite.
INVITE_CODE=$(openssl rand -hex 12)
TZ=America/New_York
# Put your own account email here to see the Operator page (usage and cost of managed AI).
ADMIN_EMAILS=
# Public https only (docker-compose.prod.yml): DOMAIN=klierly.example.com
# Managed AI is OFF until you fill in all three (see docs/MANAGED_AI.md; this starts real spending):
MANAGED_AI_BASE_URL=
MANAGED_AI_API_KEY=
MANAGED_AI_MODEL=
ENV
  echo "Created .env with new random secrets (mode 600). Edit ADMIN_EMAILS if you want the Operator page."
fi

echo
echo "Next: log out and back in once (so the docker group applies), then:"
echo "  docker compose up -d --build        # first build takes a while on 2 small cores"
echo "  curl http://localhost:3000/api/health"
